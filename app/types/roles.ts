export const ROLE_PERMISSIONS: Record<RoleName, readonly Permission[]> = {
  ADMIN_MASTER: ADMIN_MASTER_PERMISSIONS,
  ADMIN_SECUNDARIO: ADMIN_SECUNDARIO_PERMISSIONS,
  PROFESSOR: PROFESSOR_PERMISSIONS,
  ALUNO: ALUNO_PERMISSIONS,
  AUDITOR: AUDITOR_PERMISSIONS,
  SUPORTE_TECNICO: SUPORTE_TECNICO_PERMISSIONS,
};

export function permissionsForRole(role: RoleName): readonly Permission[] {
  return ROLE_PERMISSIONS[role];
}

export function hasPermission(roles: readonly RoleName[], permission: Permission): boolean {
  return roles.some((role) => ROLE_PERMISSIONS[role].includes(permission));
}

export function hasAnyPermission(
  roles: readonly RoleName[],
  permissions: readonly Permission[],
): boolean {
  return permissions.some((permission) => hasPermission(roles, permission));
}

/** Perfis que exigem segundo fator obrigatório (seção 8.4.2). */
export const MFA_REQUIRED_ROLES: readonly RoleName[] = [
  "ADMIN_MASTER",
  "ADMIN_SECUNDARIO",
  "PROFESSOR",
  "AUDITOR",
  "SUPORTE_TECNICO",
];

export function requiresMfa(roles: readonly RoleName[]): boolean {
  return roles.some((role) => MFA_REQUIRED_ROLES.includes(role));
}

/** Tempo de inatividade da sessão em segundos (seção 8.5.1). */
export function sessionInactivitySeconds(roles: readonly RoleName[]): number {
  return roles.includes("ALUNO") && roles.length === 1 ? 30 * 60 : 15 * 60;
}

